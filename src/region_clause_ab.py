def named_pull_ids(baseline: pd.DataFrame) -> list[str]:
    """The ids of the named cluster: answer-key ``global`` rows pulled to a region.

    Derived from the committed baseline rather than hardcoded. A pinned list would be a
    second source of truth for a fact the CSV already states, and it would silently
    stop describing the file the day either column moved. ADR-022 measured 17 of these
    at n=300; the report prints the count so a drift is visible rather than assumed.

    Args:
        baseline: The baseline predictions frame.

    Returns:
        Row ids, in file order, where the judge said ``global`` and the workhorse
        named a specific region.
    """
    pulled = baseline[
        (baseline["judge_region"] == GLOBAL) & (baseline["pred_region"] != GLOBAL)
    ]
    return [str(row_id) for row_id in pulled["id"]]


def cluster_delta(baseline: pd.DataFrame, candidate: pd.DataFrame) -> dict:
    """Account for the clause's effect on the named cluster and on its converse.

    Both directions, explicitly, because a clause that pushes rows toward ``global``
    cannot fix the pull without risking the over-call -- and reporting only the fixes
    is how a prompt change gets adopted on a number that nets out to zero. The n=300
    baseline already carried 10 over-called-``global`` rows before any clause existed.

    Args:
        baseline: Baseline predictions (workhorse + judge columns).
        candidate: Candidate predictions (workhorse columns only).

    Returns:
        Dict with the named-pull fix accounting, the over-call counts on both arms,
        which rows newly over-called ``global``, and the net region row change.
    """
    merged = baseline.merge(candidate, on="id", suffixes=("_base", "_cand"))
    named = merged[
        (merged["judge_region"] == GLOBAL) & (merged["pred_region_base"] != GLOBAL)
    ]
    fixed = named[named["pred_region_cand"] == GLOBAL]

    def _over(column: str) -> pd.DataFrame:
        return merged[(merged[column] == GLOBAL) & (merged["judge_region"] != GLOBAL)]

    over_base, over_cand = _over("pred_region_base"), _over("pred_region_cand")
    newly_over = over_cand[~over_cand["id"].isin(set(over_base["id"]))]

    correct_base = int((merged["pred_region_base"] == merged["judge_region"]).sum())
    correct_cand = int((merged["pred_region_cand"] == merged["judge_region"]).sum())
    return {
        "n": len(merged),
        "named_pulls": len(named),
        "named_fixed": len(fixed),
        "named_fixed_ids": [str(i) for i in fixed["id"]],
        "named_unfixed_ids": [
            str(i) for i in named[named["pred_region_cand"] != GLOBAL]["id"]
        ],
        "over_global_baseline": len(over_base),
        "over_global_candidate": len(over_cand),
        "newly_over_global": len(newly_over),
        "newly_over_global_ids": [str(i) for i in newly_over["id"]],
        "region_correct_baseline": correct_base,
        "region_correct_candidate": correct_cand,
        "region_net_rows": correct_cand - correct_base,
    }


def axis_comparison(
    baseline_path: str, candidate_path: str, axis: str, judge_column: str
) -> tuple[paired_compare.PairingResult, paired_compare.CorrectnessLift]:
    """Run one axis's paired comparison through ``paired_compare``.

    The answer key and the baseline arm are the *same file*, read twice for different
    columns: ``judge_{axis}`` is the frozen ruler, ``pred_{axis}`` is the baseline arm's
    answer. Nothing about that is a special case for ``paired_compare`` -- it already
    takes an explicit ``--truth-column`` -- so this comparison runs through the repo's
    existing, tested pairing and McNemar code rather than a private reimplementation.

    Args:
        baseline_path: The committed baseline predictions CSV.
        candidate_path: The candidate arm's predictions CSV.
        axis: ``region``, ``category``, or ``operational_domain``.
        judge_column: The answer-key column for this axis.

    Returns:
        The pairing result and the correctness summary.
    """
    answers = paired_compare.load_answer_key(
        baseline_path, axis, truth_column=judge_column
    )
    column = f"pred_{axis}"
    result = paired_compare.pair_observations(
        paired_compare.observations_from_frame(
            paired_compare.read_predictions(baseline_path), "baseline", column, answers
        ),
        paired_compare.observations_from_frame(
            paired_compare.read_predictions(candidate_path),
            "candidate",
            column,
            answers,
        ),
    )
    return result, paired_compare.summarize_correctness(result.pairs)


