GLOBAL = "global"
PRIMARY_AXIS = "region"

# (axis, judge/answer-key column). Region is the target; the other two are guardrails.
# ADR-020 is why they are not optional: the L4 critic fixed its named region cluster and
# did statistically significant damage to the domain axis (p=0.016) at the same time. A
# region-only report would have called that experiment a success.
AXES = [
    ("region", "judge_region"),
    ("category", "judge_category"),
    ("operational_domain", "judge_operational_domain"),
]

CANDIDATE_COLUMNS = ["id", "pred_category", "pred_operational_domain", "pred_region"]


# ---------------------------------------------------------------------------
# Guards. These run before any number is computed, because each one describes a
# way this comparison could produce a clean-looking result that means nothing.
# ---------------------------------------------------------------------------


def assert_resume_is_honest(done_ids: set, live: dict[str, str]) -> None:
    """Refuse to append today's classifier's rows onto yesterday's.

    Same rule ``gold_eval`` and ``scale_region_eval`` apply to their own snapshots: a
    file half-written under one prompt and half under another is a blend no single
    fingerprint can describe. A fresh run has nothing to blend and is always allowed.

    Args:
        done_ids: Ids already present in the candidate predictions CSV.
        live: A ``provenance.fingerprint`` of the current prompt and models.

    Raises:
        ValueError: If existing rows were produced by a different prompt or model.
    """
    if not done_ids or not os.path.exists(CANDIDATE_PROVENANCE_PATH):
        return
    recorded = provenance.load(CANDIDATE_PROVENANCE_PATH)["recorded"]
    drift = provenance.divergences(recorded, live)
    if not drift:
        return
    raise ValueError(
        f"Cannot resume {CANDIDATE_PREDS_PATH}: the {len(done_ids)} existing rows were "
        "produced by a different prompt or model.\n"
        + "\n".join(drift)
        + f"\n\nResuming would mix two classifiers in one arm. Delete "
        f"{CANDIDATE_PREDS_PATH} and {CANDIDATE_PROVENANCE_PATH} and re-run."
    )


def assert_arms_differ(baseline: dict[str, str], candidate: dict[str, str]) -> None:
    """Refuse to report an A/B whose two arms are not a clean prompt contrast.

    Two failure modes, both of which produce a perfectly well-formed report:

    - **Same prompt on both sides.** The candidate run was made before the clause
      landed, or against a stale checkout. The "lift" is then pure run-to-run sampling
      noise being read as an effect.
    - **A model changed too.** Then the experiment is a prompt *and* model A/B and no
      row-level difference can be attributed to the clause.

    Args:
        baseline: The ``recorded`` block of the baseline snapshot's sidecar.
        candidate: The ``recorded`` block of the candidate run's sidecar.

    Raises:
        ValueError: If the prompts match, or either model id differs.
    """
    if baseline.get("prompt_sha256") == candidate.get("prompt_sha256"):
        raise ValueError(
            "Both arms were produced by the SAME prompt "
            f"({candidate.get('prompt_sha256')}). There is no clause to measure -- any "
            f"difference would be sampling noise. Was {CANDIDATE_PREDS_PATH} produced "
            "before the clause was added, or on a checkout without it?"
        )
    for key in ("workhorse_model", "judge_model"):
        if baseline.get(key) != candidate.get(key):
            raise ValueError(
                f"The two arms disagree on {key}: baseline {baseline.get(key)!r} vs "
                f"candidate {candidate.get(key)!r}. This is a prompt A/B; a model swap "
                "makes every row-level difference unattributable. Re-run the candidate "
                "arm on the baseline's models."
            )


def assert_answer_key_is_frozen(baseline: pd.DataFrame) -> None:
    """Refuse to grade against an answer key that is not the committed baseline's.

    The whole 300-call saving rests on the judge columns being the ones ADR-022
    published. This checks the frame actually carries them, so a truncated or
    hand-assembled baseline file cannot silently become the ruler.

    Args:
        baseline: The loaded baseline predictions frame.

    Raises:
        ValueError: If any judge column is missing or any judge cell is blank.
    """
    for _axis, judge_column in AXES:
        if judge_column not in baseline.columns:
            raise ValueError(
                f"{BASELINE_PREDS_PATH} has no {judge_column!r} column, so it cannot "
                "supply the frozen answer key this comparison grades against."
            )
        blank = (baseline[judge_column].astype(str).str.strip() == "").sum()
        if blank:
            raise ValueError(
                f"{BASELINE_PREDS_PATH} has {blank} blank {judge_column!r} cells. An "
                "answer key with holes silently shrinks the comparison instead of "
                "failing it."
            )


