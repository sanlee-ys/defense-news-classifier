def _optional(value: float | None, spec: str) -> str:
    """Format an optional number, keeping 'nothing to compare' distinct from zero.

    Local rather than imported from ``paired_compare``: that module's equivalents are
    private, and reaching across a module boundary for a private helper couples this
    report to another module's internals for two lines of formatting.

    Args:
        value: The number, or ``None`` when there was nothing to compute it over.
        spec: Format spec applied when the value is present.

    Returns:
        The formatted number, or ``"n/a"``.
    """
    return "n/a" if value is None else format(value, spec)


def _cluster_block(delta: dict) -> list[str]:
    """Format the named-cluster accounting.

    Args:
        delta: Output of :func:`cluster_delta`.

    Returns:
        Report lines.
    """
    fixed_rate = (
        f"{delta['named_fixed'] / delta['named_pulls']:.0%}"
        if delta["named_pulls"]
        else "n/a"
    )
    lines = [
        "",
        "-- The named `global` cluster ------------------------------",
        "The rows the clause was written for: answer-key `global` that the",
        "BASELINE pulled to a specific region (ADR-022 measured 17 at n=300).",
        "",
        f"Named pulls in the baseline     : {delta['named_pulls']}",
        f"  fixed by the clause           : {delta['named_fixed']}   ({fixed_rate})",
        f"  still pulled                  : {len(delta['named_unfixed_ids'])}",
        "",
        "-- The converse, which is how this clause could lose --------",
        "A clause that moves rows toward `global` buys its fixes with",
        "over-calls. Both directions or neither.",
        "",
        f"Over-called `global`, baseline  : {delta['over_global_baseline']}",
        f"Over-called `global`, candidate : {delta['over_global_candidate']}",
        f"  of which NEW                  : {delta['newly_over_global']}",
        "",
        "-- Net, on region rows -------------------------------------",
        f"Region correct, baseline        : {delta['region_correct_baseline']}"
        f"/{delta['n']}",
        f"Region correct, candidate       : {delta['region_correct_candidate']}"
        f"/{delta['n']}",
        f"Net row change                  : {delta['region_net_rows']:+d}",
    ]
    if delta["named_fixed_ids"]:
        lines.append("")
        lines.append("Fixed ids       : " + ", ".join(delta["named_fixed_ids"]))
    if delta["named_unfixed_ids"]:
        lines.append("Still pulled    : " + ", ".join(delta["named_unfixed_ids"]))
    if delta["newly_over_global_ids"]:
        lines.append("Newly over-called: " + ", ".join(delta["newly_over_global_ids"]))
    return lines


def build_report(
    baseline: pd.DataFrame,
    candidate: pd.DataFrame,
    comparisons: list[
        tuple[str, paired_compare.PairingResult, paired_compare.CorrectnessLift]
    ],
    baseline_recorded: dict[str, str],
    candidate_recorded: dict[str, str],
) -> str:
    """Assemble the A/B report.

    Args:
        baseline: Baseline predictions frame.
        candidate: Candidate predictions frame.
        comparisons: ``(axis, pairing result, correctness lift)`` per axis.
        baseline_recorded: The baseline sidecar's ``recorded`` block.
        candidate_recorded: The candidate sidecar's ``recorded`` block.

    Returns:
        The report text.
    """
    delta = cluster_delta(baseline, candidate)
    lines = [
        "=" * 62,
        "`global`-BOUNDARY CLAUSE A/B -- workhorse prompt, n=300",
        "=" * 62,
        "",
        f"Snippets          : {delta['n']}   ({SCALE_SET_PATH})",
        f"Workhorse         : {candidate_recorded.get('workhorse_model')}",
        f"Answer key        : {candidate_recorded.get('judge_model')} judge labels,",
        f"                    FROZEN, reused from {BASELINE_PREDS_PATH}",
        "",
        "The judge was NOT re-run. gold_eval.run_predictions classifies each row",
        "with the workhorse and the judge independently, from the snippet text",
        "alone -- neither sees the other's answer -- so a judge label cannot",
        "depend on the workhorse's prompt. Holding it fixed is what makes this a",
        "paired comparison instead of two runs graded by two different rulers.",
        "",
        f"Baseline prompt   : {baseline_recorded.get('prompt_sha256')}",
        f"Candidate prompt  : {candidate_recorded.get('prompt_sha256')}",
        "",
        "-- Paired comparison, per axis -----------------------------",
        "Region is the target. Category and domain are GUARDRAILS: ADR-020's",
        "critic fixed its named region cluster and did significant damage to",
        "domain (p=0.016) in the same run. Significant harm on either kills",
        "this clause regardless of what region does.",
        "",
        f"{'axis':<20}{'base':>8}{'cand':>8}{'lift':>9}"
        f"{'c/b/tie':>13}{'McNemar p':>12}",
    ]
    for axis, _result, lift in comparisons:
        base = _optional(lift.baseline_pass_rate, ".1%")
        cand = _optional(lift.candidate_pass_rate, ".1%")
        shift = _optional(lift.lift, "+.1%")
        wins = f"{lift.candidate_wins}/{lift.baseline_wins}/{lift.ties}"
        lines.append(
            f"{axis:<20}{base:>8}{cand:>8}{shift:>9}{wins:>13}{lift.p_value:>12.4f}"
        )

    lines += _cluster_block(delta)
    lines += [
        "",
        "-- Harness health ------------------------------------------",
        "A lift computed over a harness that dropped rows is not a finding.",
        "",
    ]
    for axis, result, lift in comparisons:
        counts = paired_compare.diagnostic_counts(result.diagnostics)
        summary = ", ".join(f"{k}={v}" for k, v in counts.items() if v)
        lines.append(
            f"  {axis:<20} groups={result.total_groups}  pairs={lift.total_pairs}  "
            f"eligible={lift.eligible_pairs}"
        )
        lines.append(
            f"  {'':<20} {summary or 'clean -- every group paired and scored'}"
        )
    lines += [
        "",
        "-- How to read this ----------------------------------------",
        "Accuracy here is agreement with the JUDGE, not with a human. ADR-022's",
        "caveat carries over verbatim: the judge's measured disagreement with",
        "humans on region was 0/54, and 0/54 is itself a wide interval, so read",
        "these numbers alongside the human-graded gold figures, never instead of",
        "them. The gold arm is the human-graded half of this experiment.",
        "=" * 62,
    ]
    return "\n".join(lines)


