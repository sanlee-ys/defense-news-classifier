# The frozen v3.2.0 baseline arm: the committed workhorse predictions AND the judge
# labels this comparison grades both arms against. Read-only, always.
BASELINE_PREDS_PATH = "evals/scale_predictions_v3.csv"
BASELINE_PROVENANCE_PATH = "evals/scale_predictions_v3.provenance.json"

# Everything this module writes. All new paths; none of them shadow a frozen record.
CANDIDATE_PREDS_PATH = "evals/region_clause_candidate.csv"
CANDIDATE_PROVENANCE_PATH = "evals/region_clause_candidate.provenance.json"
