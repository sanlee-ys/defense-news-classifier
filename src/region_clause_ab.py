def run(batch: bool = False) -> None:
    """Run the candidate workhorse pass over the scale set, then record provenance.

    The only function here that spends API budget: 1 call per not-yet-done snippet.

    Args:
        batch: Submit via the Message Batches API instead of N synchronous calls.

    Raises:
        ValueError: If resuming would blend two different classifiers.
    """
    os.makedirs("evals", exist_ok=True)
    scale = scale_eval.load_scale_set(SCALE_SET_PATH)
    print(f"Loaded {len(scale)} snippets from {SCALE_SET_PATH}\n")

    done_ids = (
        set(pd.read_csv(CANDIDATE_PREDS_PATH)["id"])
        if os.path.exists(CANDIDATE_PREDS_PATH)
        else set()
    )
    if done_ids:
        print(f"Resuming: {len(done_ids)} already predicted.\n")
    if not set(scale["id"]) - done_ids:
        print("All predictions already present -- skipping API calls.\n")
        return

    live = provenance.fingerprint(SYSTEM_PROMPT, WORKHORSE_MODEL, JUDGE_MODEL)
    assert_resume_is_honest(done_ids, live)

    client = make_client()
    # Passed explicitly rather than relying on the default: a default argument binds at
    # definition time, so a caller (or a test) that repoints CANDIDATE_PREDS_PATH would
    # otherwise be silently ignored and write to the module-level path anyway.
    if batch:
        run_workhorse_batch(client, scale, done_ids, preds_path=CANDIDATE_PREDS_PATH)
    else:
        run_workhorse(client, scale, done_ids, preds_path=CANDIDATE_PREDS_PATH)

    # Written only on the path that made API calls, so a report-only rerun can never
    # assert that today's prompt produced yesterday's rows.
    provenance.write(live, CANDIDATE_PREDS_PATH, path=CANDIDATE_PROVENANCE_PATH)
    print(f"Recorded run provenance to {CANDIDATE_PROVENANCE_PATH}\n")


def report() -> str:
    """Score the two committed arms and write the report.

    Entirely offline: no client, no key, no API call.

    Returns:
        The report text.

    Raises:
        FileNotFoundError: If either sidecar is missing -- an unknown pairing must not
            read as a verified one.
        ValueError: If a guard finds the comparison would not mean what it claims.
    """
    os.makedirs("evals", exist_ok=True)
    baseline = pd.read_csv(BASELINE_PREDS_PATH)
    candidate = pd.read_csv(CANDIDATE_PREDS_PATH)
    assert_answer_key_is_frozen(baseline)

    baseline_recorded = provenance.load(BASELINE_PROVENANCE_PATH)["recorded"]
    candidate_recorded = provenance.load(CANDIDATE_PROVENANCE_PATH)["recorded"]
    assert_arms_differ(baseline_recorded, candidate_recorded)

    comparisons = [
        (axis, *axis_comparison(BASELINE_PREDS_PATH, CANDIDATE_PREDS_PATH, axis, col))
        for axis, col in AXES
    ]
    text = (
        build_report(
            baseline, candidate, comparisons, baseline_recorded, candidate_recorded
        )
        + "\n"
    )
    atomic_write_text(REPORT_PATH, text)
    return text


def main() -> None:
    """CLI entrypoint: ``--run`` spends API budget, ``--report`` never does."""
    parser = argparse.ArgumentParser(
        description="A/B the `global`-boundary prompt clause against the n=300 ruler."
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="LIVE: classify the scale set with the workhorse under the current prompt "
        "(~N calls; the judge is NOT re-run).",
    )
    parser.add_argument(
        "--batch",
        action="store_true",
        help="with --run, submit via the Message Batches API (~50%% cheaper, "
        "non-interactive).",
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="OFFLINE: score the two committed arms and write the report.",
    )
    args = parser.parse_args()

    if not args.run and not args.report:
        parser.error("nothing to do: pass --run and/or --report")
    if args.batch and not args.run:
        parser.error("--batch only applies to --run")
    if args.run:
        run(batch=args.batch)
    if args.report:
        print(report())


if __name__ == "__main__":
    main()
