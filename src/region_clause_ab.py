"""A/B the `global`-boundary prompt clause against the v3.2.0 n=300 ruler.

WHAT THIS MEASURES. `evals/scale_predictions_v3.csv` (ADR-022) recorded, for each of
300 DVIDS snippets, a workhorse label and an Opus-judge label. 17 of the 70 answer-key
``global`` rows were pulled to a specific region -- 16 to ``americas`` -- which is 49%
of every region disagreement in that run. The prompt clause added alongside this module
targets exactly that pull. This harness measures whether it works, and what it costs on
the other two axes.

THE CHEAP TRICK, AND WHY IT IS SOUND. A candidate arm normally costs 600 calls: 300
workhorse + 300 judge. It costs **300 here**, because the judge labels are reused from
the committed baseline snapshot rather than re-run. That is legitimate for one specific,
verifiable reason: ``gold_eval.run_predictions`` classifies each row with the workhorse
and the judge **independently, from the snippet text alone** -- neither model is shown
the other's answer. So a judge label is a function of (snippet, judge model, judge
prompt) and carries no dependence whatsoever on the workhorse's prediction. Changing the
workhorse's prompt cannot change what the judge would have said about that row.

Reusing the stored labels is therefore not a shortcut around a measurement, it is the
*correct* design: an answer key that moved between arms would confound the comparison
outright. The judge stays frozen at the values ADR-022 published, so the two arms are
graded by one identical ruler and every row difference is attributable to the prompt.

Note the direction of that argument carefully. ``classify()`` defaults BOTH models to
``classify.SYSTEM_PROMPT``, so a *fresh* judge pass on this branch would grade under the
new prompt and produce a different, prompt-confounded answer key. Not re-running the
judge is what keeps the key fixed. :func:`assert_answer_key_is_frozen` enforces that the
key really is the committed baseline's, and :func:`assert_arms_differ` enforces that the
two arms differ by the prompt and nothing else.

WHAT IS NEVER TOUCHED. Every artifact this writes is new and `region_clause`-named. The
v3.2.0 records (``evals/scale_predictions_v3.csv`` and its sidecar, ``scale_eval_v3.txt``,
``scale_confusion_v3_region.csv``) are a shipped, frozen measurement and are opened
read-only. Nothing here writes to ``evals/thresholds.toml``, ``evals/metrics.json``, or
any gold artifact.

A NEW MODULE, NOT A MODE ON ``scale_region_eval``. Same reasoning that spec used for not
extending ``scale_eval``: that module owns frozen outputs, and giving it a second write
path is how a frozen record eventually gets regenerated by someone reaching for the
nearest flag. This module imports the shared prediction pieces and owns only new paths.

Run -- the live pass is owner-driven (300 workhorse calls); the report is free:

    uv run --env-file .env python src/region_clause_ab.py --run
    uv run --env-file .env python src/region_clause_ab.py --run --batch
    uv run python src/region_clause_ab.py --report

``--run`` is resume-safe: rows append as they land and a re-run skips ids already
present. A resume across a prompt or model change is refused rather than blended.
``--report`` makes no API call, needs no key, and is repeatable.
"""

